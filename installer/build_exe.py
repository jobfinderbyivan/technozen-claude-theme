"""Builds installer/Technozen for Claude.exe, and Technozen tests.exe with the self-test, benchmark and demo,
using the C# compiler that ships in every Windows 10/11 (.NET Framework 4.x), so no SDK is needed.
Run: python installer/build_exe.py (after build.py)."""
import gzip
import pathlib
import subprocess
import sys

VERSION = "1.4.1"   # shown in the installer's title bar and used for the release file name
HERE = pathlib.Path(__file__).parent
SNIPPET = HERE.parent / "dist" / "technozen.snippet.js"
CSC = pathlib.Path(r"C:\Windows\Microsoft.NET\Framework64\v4.0.30319\csc.exe")
SOURCES = ["TechnozenInstaller.cs", "Orbs.cs", "Snippet.cs"]
SNIPPET_CS = """// Generated by build_exe.py. The theme itself is a compressed resource, unpacked only when it is pasted.
using System.IO;
using System.IO.Compression;
static class Snippet
{
    public const string Version = "%s";
    public static string Text
    {
        get
        {
            using (var z = new GZipStream(typeof(Snippet).Assembly.GetManifestResourceStream("snippet.gz"), CompressionMode.Decompress))
            using (var r = new StreamReader(z, System.Text.Encoding.UTF8)) return r.ReadToEnd();
        }
    }
}
"""


def compile_exe(name, extra_args, extra_sources):
    out = HERE / name
    cmd = [str(CSC), "/nologo", "/target:winexe", "/optimize+", f"/out:{out}", f"/win32manifest:{HERE / 'app.manifest'}",
           f"/resource:{HERE / 'snippet.gz'},snippet.gz", "/r:System.Windows.Forms.dll", "/r:System.Drawing.dll", "/r:Microsoft.CSharp.dll",
           *extra_args, *[str(HERE / s) for s in SOURCES + extra_sources]]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(r.stdout + r.stderr)
    print(f"built {name} {VERSION}: {out.stat().st_size // 1024} KB")


def main():
    if not SNIPPET.exists():
        sys.exit("dist/technozen.snippet.js is missing; run build.py first")
    if not CSC.exists():
        sys.exit(f"{CSC} not found; this build step needs Windows with .NET Framework 4.x")
    (HERE / "snippet.gz").write_bytes(gzip.compress(SNIPPET.read_bytes(), 9, mtime=0))
    (HERE / "Snippet.cs").write_text(SNIPPET_CS % VERSION, encoding="utf-8", newline="\n")
    compile_exe("Technozen for Claude.exe", [], [])
    compile_exe("Technozen tests.exe", ["/define:TESTS"], ["SelfTest.cs"])


if __name__ == "__main__":
    main()
