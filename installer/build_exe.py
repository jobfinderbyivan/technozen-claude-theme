"""Builds installer/Technozen for Claude.exe with the C# compiler that ships in every Windows 10/11
(.NET Framework 4.x), so no SDK is needed. Run: python installer/build_exe.py (after build.py)."""
import base64
import pathlib
import subprocess
import sys

VERSION = "1.3.5"   # shown in the installer's title bar and used for the release file name
HERE = pathlib.Path(__file__).parent
SNIPPET = HERE.parent / "dist" / "technozen.snippet.js"
CSC = pathlib.Path(r"C:\Windows\Microsoft.NET\Framework64\v4.0.30319\csc.exe")
OUT = HERE / "Technozen for Claude.exe"


def main():
    if not SNIPPET.exists():
        sys.exit("dist/technozen.snippet.js is missing; run build.py first")
    if not CSC.exists():
        sys.exit(f"{CSC} not found; this build step needs Windows with .NET Framework 4.x")
    # The snippet travels inside the EXE as base64, so no C# string escaping can corrupt it.
    b64 = base64.b64encode(SNIPPET.read_bytes()).decode("ascii")
    (HERE / "Snippet.cs").write_text(
        "// Generated by build_exe.py from dist/technozen.snippet.js. Do not edit.\n"
        "static class Snippet\n{\n"
        f'    public const string Version = "{VERSION}";\n'
        '    public static readonly string Text = System.Text.Encoding.UTF8.GetString(System.Convert.FromBase64String("' + b64 + '"));\n'
        "}\n", encoding="utf-8", newline="\n")
    cmd = [str(CSC), "/nologo", "/target:winexe", "/optimize+", f"/out:{OUT}", f"/win32manifest:{HERE / 'app.manifest'}",
           "/r:System.Windows.Forms.dll", "/r:System.Drawing.dll", "/r:Microsoft.CSharp.dll",
           str(HERE / "TechnozenInstaller.cs"), str(HERE / "Orbs.cs"), str(HERE / "Snippet.cs")]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(r.stdout + r.stderr)
    print(f"built {OUT.name} {VERSION}: {OUT.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
